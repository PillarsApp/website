// Reads every published timetable in data/timetables/, checks it against the data contract and writes
// src/generated/timetables.ts for the Worker. A missing directory or an empty one is fine: the cities
// whose timetable is absent fall back to the calculation.
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { basename } from "node:path";
import { fileURLToPath } from "node:url";

const root = (p) => fileURLToPath(new URL(`../${p}`, import.meta.url));
const DATA_DIR = root("data/timetables/");
const GENERATED = root("src/generated/timetables.ts");

const DATE_RE = /^\d{4}-\d{2}-\d{2}$/;
const TIME_RE = /^([01]\d|2[0-3]):[0-5]\d$/;
const COLUMNS = ["fajr", "sunrise", "dhuhr", "asr1", "asr2", "maghrib", "isha"];

class Malformed extends Error {}

function parseTimetable(file, raw) {
  const fail = (msg) => { throw new Malformed(`data/timetables/${basename(file)}: ${msg}`); };
  let t;
  try { t = JSON.parse(raw); } catch (e) { fail(`not JSON (${e.message})`); }
  if (!t || typeof t !== "object" || Array.isArray(t)) fail("top level is not an object");
  const stem = basename(file, ".json");
  if (t.id !== stem) fail(`id "${t.id}" does not match the file name "${stem}"`);
  for (const key of ["name", "publisher", "zone"]) if (typeof t[key] !== "string" || !t[key]) fail(`"${key}" must be a non-empty string`);
  if (!Array.isArray(t.sources) || !t.sources.every((s) => typeof s === "string")) fail('"sources" must be an array of strings');
  if (typeof t.retrieved !== "string" || !DATE_RE.test(t.retrieved)) fail('"retrieved" must be an ISO date');
  if (!Array.isArray(t.corrections)) fail('"corrections" must be an array');
  for (const c of t.corrections) {
    if (!c || typeof c !== "object" || !DATE_RE.test(c.date ?? "") || !COLUMNS.includes(c.field) || typeof c.why !== "string") fail(`bad correction ${JSON.stringify(c)}`);
  }
  if (!t.days || typeof t.days !== "object" || Array.isArray(t.days)) fail('"days" must be an object');
  const dates = Object.keys(t.days);
  if (!dates.length) fail('"days" is empty');
  let prevDate = "";
  for (const date of dates) {
    if (!DATE_RE.test(date)) fail(`day "${date}" is not an ISO date`);
    if (date <= prevDate) fail(`days are not sorted ascending at ${date}`);
    prevDate = date;
    const row = t.days[date];
    if (!Array.isArray(row) || row.length !== 7) fail(`${date}: expected 7 entries [${COLUMNS.join(", ")}]`);
    let prev = "";
    row.forEach((v, i) => {
      if (v === null) return;
      if (typeof v !== "string" || !TIME_RE.test(v)) fail(`${date}: ${COLUMNS[i]} "${v}" is not HH:MM`);
      if (v <= prev) fail(`${date}: ${COLUMNS[i]} ${v} is not after the previous column ${prev}`);
      prev = v;
    });
  }
  return { id: t.id, zone: t.zone, retrieved: t.retrieved, days: t.days };
}

export async function bundleTimetables() {
  let files = [];
  try { files = (await readdir(DATA_DIR)).filter((f) => f.endsWith(".json")).sort(); } catch (e) { if (e.code !== "ENOENT") throw e; }
  const entries = [];
  for (const f of files) {
    const t = parseTimetable(f, await readFile(DATA_DIR + f, "utf8"));
    entries.push(`  ${JSON.stringify(t.id)}: parse(${JSON.stringify(JSON.stringify(t))}),`);
    console.log(`timetable ${t.id}: ${Object.keys(t.days).length} days, retrieved ${t.retrieved}`);
  }
  if (!files.length) console.log("timetables: none in data/timetables/, every city calculates");
  await mkdir(root("src/generated"), { recursive: true });
  await writeFile(GENERATED, `// GENERATED by scripts/timetable-data.mjs from data/timetables/*.json. Do not edit.
import type { Timetable, TimetableId } from "../types";

const parse = (json: string) => JSON.parse(json) as Timetable;

export const TIMETABLES = {
${entries.join("\n")}
} satisfies Partial<Record<TimetableId, Timetable>>;
`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  try {
    await bundleTimetables();
  } catch (e) {
    if (!(e instanceof Malformed)) throw e;
    console.error(e.message);
    process.exit(1);
  }
}
