import { build } from "esbuild";
import { createHash } from "node:crypto";
import { existsSync, watch } from "node:fs";
import { readFile, writeFile, readdir, unlink, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { bundleTimetables } from "./timetable-data.mjs";

const root = (p) => fileURLToPath(new URL(`../${p}`, import.meta.url));
const SRC = root("page/city.js");
const OUT_DIR = root("public/prayer-times/_/");
const GENERATED = root("src/generated/client.ts");
const TEMPLATE = root("page/template.html");
const URL_PREFIX = "/prayer-times/_";

async function lintTemplate() {
  const html = await readFile(TEMPLATE, "utf8");
  const problems = [];
  for (const [, attr, value] of html.matchAll(/\b(href|src)="([^"]*)"/g)) {
    if (/^(https?:|\/\/|#|mailto:|data:)/.test(value)) continue;
    if (value.startsWith("/prayer-times/_/")) {
      if (!existsSync(root(`public${value}`))) problems.push(`${attr}="${value}" has no file under public/`);
    } else if (value.startsWith("/prayer-times")) {
      problems.push(`${attr}="${value}" is a hand-typed route: take it from PageLinks (src/routes.ts)`);
    } else if (!value.startsWith("/")) {
      problems.push(`${attr}="${value}" is relative: it breaks at /prayer-times/{country}/{city}/`);
    }
  }
  if (problems.length) {
    console.error(`page/template.html:\n  ${problems.join("\n  ")}`);
    process.exit(1);
  }
}

async function once() {
  await lintTemplate();
  await bundleTimetables();
  const result = await build({ entryPoints: [SRC], minify: true, target: "es2017", write: false, logLevel: "warning" });
  const code = result.outputFiles[0].contents;
  const hash = createHash("sha1").update(code).digest("hex").slice(0, 8);
  await mkdir(OUT_DIR, { recursive: true });
  for (const f of await readdir(OUT_DIR)) if (/^city\.[0-9a-f]+\.js$/.test(f)) await unlink(`${OUT_DIR}${f}`);
  await writeFile(`${OUT_DIR}city.${hash}.js`, code);
  await mkdir(root("src/generated"), { recursive: true });
  await writeFile(GENERATED, `// GENERATED by scripts/client.mjs. Do not edit.
export const CLIENT_SCRIPT = "${URL_PREFIX}/city.${hash}.js";
export const BUILD_ID = "${hash}-${Date.now()}";
`);
  console.log(`client ${URL_PREFIX}/city.${hash}.js`);
}

await once();
if (process.argv.includes("--watch")) {
  let timer;
  watch(SRC, () => {
    clearTimeout(timer);
    timer = setTimeout(() => once().catch((e) => console.error(e.message)), 50);
  });
}
